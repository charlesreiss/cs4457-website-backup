## all the options here can be overriden on the command-line ##

"""one of 'one-zero' or 'sliding-window' or 'variable-sliding'"""
MODE = 'one-zero'

"""initial window size for 'sliding-window' mode"""
INITIAL_WINDOW = 5


"""maximum window size for `variable-sliding` mode."""
MAXIMUM_WINDOW = 100

"""default timeout to use for resending packets."""
INITIAL_TIMEOUT = 100

"""types of events to output trace info for.

'all' matches all event, otherwise, name listed much last type passed as first arg to trace() function."""
TRACE = set([])

"""If set to true, packets being dropped due to a full buffer trigger an error message.

I recommend setting this to True for part 1 (where we never expect more than one
packet buffered) and for part 2 if you should be sending slower than the bandwidth of
the simulated link."""
BUFFER_DROP_IS_ERROR = False

"""If set to true, 'ERROR: ' messages (generated by util.error())
terminate the program."""
ERROR_IS_CRASH = True

"""Maximum sequence number accepted."""
MAXIMUM_SEQUENCE = 1000000000
